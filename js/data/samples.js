export function sampleTools(machine, id) {
  const t = defaultTools(machine);
  if (id === 'lathe-cycles') {
    // single finishing tool is enough
    return t;
  }
  return t;
}

export function sampleById(id) {
  return SAMPLES.find((s) => s.id === id);
}

